def add_locale(locale: str, strings: dict) -> int:
    path = ROOT / "lib" / "l10n" / f"app_{locale}.arb"
    text = path.read_text(encoding="utf-8")
    missing = [k for k in strings if f'"{k}":' not in text]
    if not missing:
        return 0
    lines = []
    for key in missing:
        value = json.dumps(strings[key], ensure_ascii=False)
        lines.append(f'  "{key}": {value},')
        lines.append(f'  "@{key}": {{}},')
    # 最后一条后面不能留逗号（紧跟文件结束的 `}`）
    lines[-1] = lines[-1].rstrip(",")
    block = "\n".join(lines)
    stripped = text.rstrip()
    assert stripped.endswith("}"), f"{path} 结尾不是 }}"
    # 末尾 `}` 前补逗号 + 新增块
    head = stripped[:-1].rstrip()
    assert head.endswith(("}", ",")), f"{path} 末尾条目格式异常"
    if head.endswith("}"):
        head += ","
    new_text = f"{head}\n{block}\n}}\n"
    json.loads(new_text)  # 语法自检
    path.write_text(new_text, encoding="utf-8")
    return len(missing)


def main() -> int:
    total = 0
    for locale, strings in STRINGS.items():
        n = add_locale(locale, strings)
        print(f"app_{locale}.arb: 新增 {n} 个 key")
        total += n
    if total:
        print("下一步：flutter gen-l10n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
